#!/usr/bin/env node
// Merge a "new tasks" results payload into the base payload (latest.json), so we
// can add tasks without re-running the whole matrix. Appends tasks + per-run
// taskResults (matched by run id), then regenerates the web data module.
//
// Usage: node merge.mjs --base <latest.json> --add <new.json> [--no-generated]
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "../..");

const args = { base: join(ROOT, "packages/token-board-core/benchmark/results/latest.json"), add: "", noGenerated: false };
for (let i = 2; i < process.argv.length; i++) {
  const k = process.argv[i];
  if (k === "--base") args.base = process.argv[++i];
  else if (k === "--add") args.add = process.argv[++i];
  else if (k === "--no-generated") args.noGenerated = true;
}
if (!args.add) { console.error("merge: --add <file> required"); process.exit(1); }

const base = JSON.parse(readFileSync(args.base, "utf8"));
const add = JSON.parse(readFileSync(args.add, "utf8"));

const haveTask = new Set(base.tasks.map((t) => t.id));
let addedTasks = 0;
for (const t of add.tasks) if (!haveTask.has(t.id)) { base.tasks.push(t); haveTask.add(t.id); addedTasks++; }

const runById = new Map(base.runs.map((r) => [r.id, r]));
let appended = 0;
for (const r of add.runs) {
  const existing = runById.get(r.id);
  if (existing) {
    const have = new Set(existing.taskResults.map((x) => x.taskId));
    for (const tr of r.taskResults) if (!have.has(tr.taskId)) { existing.taskResults.push(tr); appended++; }
  } else {
    base.runs.push(r);
    runById.set(r.id, r);
    appended += r.taskResults.length;
  }
}

base.generatedAt = add.generatedAt || base.generatedAt;
writeFileSync(args.base, JSON.stringify(base, null, 2));
if (!args.noGenerated) {
  const genPath = join(ROOT, "packages/token-board-core/src/benchmark-data.generated.ts");
  writeFileSync(genPath, "// AUTO-GENERATED by tools/eval-runner. Do not edit by hand.\nexport const BENCHMARK_DATA = " + JSON.stringify(base, null, 2) + " as const;\n");
  console.error(`[merge] wrote ${genPath}`);
}
console.error(`[merge] +${addedTasks} tasks, +${appended} task-results -> ${base.tasks.length} tasks total`);
